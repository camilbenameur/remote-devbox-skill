#!/usr/bin/env bash
# 10-root-bootstrap.sh: prepares a fresh Ubuntu 24.04 host for Claude Code sessions over SSH
# (Claude desktop app "SSH environments").
#
# Usage:
#   sudo bash 10-root-bootstrap.sh <user> '<ssh public key>' [initial user]
#       installation; SSH stays open to the initial user (root or ubuntu)
#       until the connection of <user> has been tested.
#   sudo bash 10-root-bootstrap.sh --lock-ssh <user>
#       run once "ssh devbox" is verified: SSH restricted to <user>, root login forbidden.
#
# Optional variables: SWAP_GB=8  SUDO_NOPASSWD=1|0  NODE_MAJOR=24  PW_MCP_VERSION=0.0.84
#                     TIMEZONE=<tz name, for example Europe/Paris>  (left unchanged if unset)
# The script can be re-run: every step checks what already exists.
#
# Architectures: amd64 is the tested path. arm64 (for example Oracle Cloud Always Free
# Ampere A1) is best effort and NOT tested end to end: Google Chrome has no Linux arm64
# build, so Playwright's Chromium is used instead.
set -euo pipefail

SWAP_GB="${SWAP_GB:-8}"
SUDO_NOPASSWD="${SUDO_NOPASSWD:-1}"
NODE_MAJOR="${NODE_MAJOR:-24}"
PW_MCP_VERSION="${PW_MCP_VERSION:-0.0.84}"
TIMEZONE="${TIMEZONE:-}"
SSHD_DROPIN=/etc/ssh/sshd_config.d/01-devbox.conf
LOCK_MARK=/etc/ssh/devbox-ssh-locked

log()  { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33m[warning] %s\033[0m\n' "$*" >&2; }
die()  { printf '\033[1;31m[error] %s\033[0m\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "Run as root: sudo bash $0 $*"

valid_user() { [[ "$1" =~ ^[a-z_][a-z0-9_-]{0,31}$ ]]; }

# Writes the sshd config. $1 = allowed users, $2 = value of PermitRootLogin.
write_sshd() {
  local allow="$1" root_login="$2"
  # 01- is read before 50-cloud-init.conf: for sshd, the first value read wins.
  cat > "$SSHD_DROPIN.new" <<EOF
# Generated by 10-root-bootstrap.sh (devbox)
PubkeyAuthentication yes
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitRootLogin $root_login
AllowUsers $allow
# The desktop app opens at least 2 connections, plus one per terminal tab.
MaxSessions 20
MaxStartups 20:30:60
ClientAliveInterval 30
ClientAliveCountMax 6
# ssh -L to reach dev servers; no reverse tunnels.
AllowTcpForwarding local
X11Forwarding no
EOF
  local old=""
  [ -f "$SSHD_DROPIN" ] && old="$(cat "$SSHD_DROPIN")"
  mv "$SSHD_DROPIN.new" "$SSHD_DROPIN"
  # Output captured: with pipefail, grep -q can cut off sshd -T (SIGPIPE) and skew the test.
  local effective
  effective="$(/usr/sbin/sshd -T 2>/dev/null || true)"
  if ! grep -qi '^subsystem sftp' <<<"$effective"; then
    echo "Subsystem sftp /usr/lib/openssh/sftp-server" >> "$SSHD_DROPIN"
  fi
  if ! /usr/sbin/sshd -t; then
    if [ -n "$old" ]; then printf '%s\n' "$old" > "$SSHD_DROPIN"; else rm -f "$SSHD_DROPIN"; fi
    die "Invalid sshd configuration: previous configuration restored."
  fi
  systemctl restart ssh   # connections that are already open stay open
  sleep 1
  [ -n "$(ss -H -ltn '( sport = :22 )')" ] || die "sshd is no longer listening on port 22: use your hosting provider's console."
}

# ---------------------------------------------------------------- --lock-ssh mode
if [ "${1:-}" = "--lock-ssh" ]; then
  DEV_USER="${2:-}"
  valid_user "$DEV_USER" || die "Usage: sudo bash $0 --lock-ssh <user>"
  DEV_HOME="$(getent passwd "$DEV_USER" | cut -d: -f6)"
  [ -s "$DEV_HOME/.ssh/authorized_keys" ] || die "No key for $DEV_USER: lock cancelled."
  log "SSH restricted to $DEV_USER, root login forbidden"
  write_sshd "$DEV_USER" no
  touch "$LOCK_MARK"
  echo "Done. Other accounts (root, ubuntu) can no longer log in over SSH."
  exit 0
fi

DEV_USER="${1:-}"
DEV_PUBKEY="${2:-}"
INITIAL_USER="${3:-${SUDO_USER:-root}}"
[ -n "$DEV_USER" ] || die "Usage: sudo bash $0 <user> '<ssh public key>' [initial user]"
valid_user "$DEV_USER" || die "Invalid user name: $DEV_USER"
valid_user "$INITIAL_USER" || die "Invalid initial user: $INITIAL_USER"
case "$SUDO_NOPASSWD" in 0|1) ;; *) die "SUDO_NOPASSWD must be 0 or 1" ;; esac

. /etc/os-release
if [ "${ID:-}" != "ubuntu" ] || [ "${VERSION_ID:-}" != "24.04" ]; then
  warn "Script written for Ubuntu 24.04, found: ${PRETTY_NAME:-unknown}. Continuing."
fi
ARCH="$(dpkg --print-architecture)"   # amd64 or arm64
case "$ARCH" in amd64|arm64) ;; *) die "Unsupported architecture: $ARCH" ;; esac
export DEBIAN_FRONTEND=noninteractive
# DPkg::Lock::Timeout: wait for the dpkg lock instead of failing (first boot).
APT_OPTS=(-y -o DPkg::Lock::Timeout=600 -o Dpkg::Options::=--force-confdef -o Dpkg::Options::=--force-confold)

# The package lists lock does not honour DPkg::Lock::Timeout: retry.
apt_update() {
  local i
  for i in $(seq 1 60); do
    apt-get update && return 0
    warn "apt is busy (first-boot updates?), retrying in 10 s ($i/60)"
    sleep 10
  done
  die "apt-get update keeps failing."
}

# ---------------------------------------------------------------- packages
log "Waiting for first boot to finish (cloud-init)"
if command -v cloud-init >/dev/null 2>&1; then
  cloud-init status --wait >/dev/null 2>&1 || true
fi

log "System update and base packages"
apt_update
apt-get "${APT_OPTS[@]}" upgrade
apt-get "${APT_OPTS[@]}" install --no-install-recommends \
  ca-certificates curl wget gnupg sudo openssh-server openssh-sftp-server iproute2 \
  git git-lfs tmux jq ripgrep fd-find unzip zip htop ncdu tree \
  build-essential python3 python3-venv python3-pip pipx \
  ufw fail2ban python3-systemd unattended-upgrades \
  bubblewrap socat zram-tools \
  fonts-liberation fonts-noto-color-emoji \
  tigervnc-standalone-server tigervnc-tools novnc python3-websockify openbox tint2 xdg-utils

# ---------------------------------------------------------------- user
log "User $DEV_USER"
if ! id "$DEV_USER" >/dev/null 2>&1; then
  adduser --disabled-password --gecos "" "$DEV_USER"
fi
usermod -aG sudo "$DEV_USER"
SUDOERS_FILE="/etc/sudoers.d/90-$DEV_USER"
if [ "$SUDO_NOPASSWD" = "1" ]; then
  echo "$DEV_USER ALL=(ALL) NOPASSWD:ALL" > "$SUDOERS_FILE.tmp"
  chmod 440 "$SUDOERS_FILE.tmp"
  visudo -cf "$SUDOERS_FILE.tmp" >/dev/null || die "Invalid sudoers file"
  mv "$SUDOERS_FILE.tmp" "$SUDOERS_FILE"
else
  rm -f "$SUDOERS_FILE"
  if [ "$(passwd -S "$DEV_USER" | awk '{print $2}')" != "P" ]; then
    warn "$DEV_USER has no password: sudo will not work until you run 'passwd $DEV_USER' (as root)."
  fi
fi

DEV_HOME="$(getent passwd "$DEV_USER" | cut -d: -f6)"
install -d -m 700 -o "$DEV_USER" -g "$DEV_USER" "$DEV_HOME/.ssh"
AUTH_KEYS="$DEV_HOME/.ssh/authorized_keys"
touch "$AUTH_KEYS"

# Keys to authorize: the one passed as argument, otherwise those of the initial
# user (root or ubuntu), without options such as command="..." that some
# hosting providers prepend to root's keys.
KEY_RE='(ssh-ed25519|ssh-rsa|ecdsa-sha2-nistp[0-9]+|sk-ssh-ed25519@openssh\.com|sk-ecdsa-sha2-nistp256@openssh\.com) [A-Za-z0-9+/=]+( [^[:cntrl:]]*)?'
add_key() {
  local k core
  k="$(printf '%s' "$1" | tr -d '\r' | grep -Eo "$KEY_RE" | head -n1 || true)"
  [ -n "$k" ] || return 0
  core="$(printf '%s' "$k" | awk '{print $1" "$2}')"   # type + key, without the comment
  grep -qF "$core" "$AUTH_KEYS" || printf '%s\n' "$k" >> "$AUTH_KEYS"
}
if [ -n "$DEV_PUBKEY" ]; then
  add_key "$DEV_PUBKEY"
else
  for f in "/home/${SUDO_USER:-__none__}/.ssh/authorized_keys" /root/.ssh/authorized_keys; do
    [ -s "$f" ] || continue
    while IFS= read -r line || [ -n "$line" ]; do add_key "$line"; done < "$f"
  done
fi
chown "$DEV_USER:$DEV_USER" "$AUTH_KEYS"
chmod 600 "$AUTH_KEYS"
[ -s "$AUTH_KEYS" ] || die "No SSH key for $DEV_USER: leaving the SSH configuration alone."

# ---------------------------------------------------------------- sshd
if [ -f "$LOCK_MARK" ]; then
  log "SSH configuration (already locked: $DEV_USER only)"
  write_sshd "$DEV_USER" no
else
  # The initial user keeps access (key only) until "ssh devbox" has been
  # verified; the client setup script then locks SSH with --lock-ssh.
  log "SSH configuration (keys only; $INITIAL_USER keeps access until the lock)"
  if [ "$INITIAL_USER" = "root" ]; then
    write_sshd "$DEV_USER root" prohibit-password
  else
    write_sshd "$DEV_USER $INITIAL_USER" no
  fi
fi

# ---------------------------------------------------------------- persistent sessions
log "Processes of $DEV_USER survive SSH disconnection"
mkdir -p /etc/systemd/logind.conf.d
printf '[Login]\nKillUserProcesses=no\n' > /etc/systemd/logind.conf.d/90-devbox.conf
loginctl enable-linger "$DEV_USER"

# ---------------------------------------------------------------- memory
log "Swap ${SWAP_GB} GB + zram (safety net for Chrome and Claude sessions)"
if [ "$SWAP_GB" -gt 0 ] && ! swapon --show=NAME --noheadings | grep -qx /swapfile; then
  if [ ! -f /swapfile ]; then
    fallocate -l "${SWAP_GB}G" /swapfile 2>/dev/null || dd if=/dev/zero of=/swapfile bs=1M count=$((SWAP_GB * 1024)) status=none
    chmod 600 /swapfile
    mkswap /swapfile >/dev/null
  fi
  if swapon -p 10 /swapfile 2>/dev/null; then
    grep -q '^/swapfile ' /etc/fstab || echo '/swapfile none swap sw,pri=10 0 0' >> /etc/fstab
  else
    warn "Disk swap is not possible on this host (continuing with zram only)."
  fi
fi
cat > /etc/default/zramswap <<'EOF'
ALGO=zstd
PERCENT=25
PRIORITY=100
EOF
# Some provider kernels have no zram module: keep disk swap only in that case.
if modprobe zram 2>/dev/null; then
  systemctl restart zramswap 2>/dev/null || warn "zramswap did not start (not blocking)."
else
  systemctl disable --now zramswap >/dev/null 2>&1 || true
  systemctl reset-failed zramswap >/dev/null 2>&1 || true
  echo "No zram module in this kernel: disk swap only."
fi

cat > /etc/sysctl.d/90-devbox.conf <<'EOF'
# Many Node/Claude sessions and file-watching tools.
fs.inotify.max_user_watches = 524288
fs.inotify.max_user_instances = 1024
vm.swappiness = 60
EOF
sysctl --system >/dev/null

# ---------------------------------------------------------------- tools
log "Node.js $NODE_MAJOR (NodeSource)"
if ! command -v node >/dev/null 2>&1 || [ "$(node -p 'process.versions.node.split(".")[0]')" -lt "$NODE_MAJOR" ]; then
  curl -fsSL "https://deb.nodesource.com/setup_${NODE_MAJOR}.x" -o /tmp/nodesource_setup.sh
  bash /tmp/nodesource_setup.sh
  apt-get "${APT_OPTS[@]}" install nodejs
  rm -f /tmp/nodesource_setup.sh
fi

log "GitHub CLI (official repository)"
if ! command -v gh >/dev/null 2>&1; then
  install -d -m 755 /etc/apt/keyrings
  wget -qO /etc/apt/keyrings/githubcli-archive-keyring.gpg https://cli.github.com/packages/githubcli-archive-keyring.gpg
  chmod go+r /etc/apt/keyrings/githubcli-archive-keyring.gpg
  echo "deb [arch=$ARCH signed-by=/etc/apt/keyrings/githubcli-archive-keyring.gpg] https://cli.github.com/packages stable main" \
    > /etc/apt/sources.list.d/github-cli.list
  apt_update
  apt-get "${APT_OPTS[@]}" install gh
fi

log "Browser for Playwright MCP"
if [ "$ARCH" = "amd64" ]; then
  if ! command -v google-chrome-stable >/dev/null 2>&1; then
    wget -qO /tmp/google-chrome.deb https://dl.google.com/linux/direct/google-chrome-stable_current_amd64.deb
    apt-get "${APT_OPTS[@]}" install /tmp/google-chrome.deb   # also adds the Google repository for updates
    rm -f /tmp/google-chrome.deb
  fi
else
  # arm64 (best effort, not tested end to end): Google Chrome does not exist for Linux
  # arm64, so skip the .deb and install the system libraries that Playwright's Chromium
  # needs. 20-user-setup.sh installs the Chromium itself, in the playwright version
  # bundled with the pinned MCP.
  PW_VERSION="$(npm view "@playwright/mcp@${PW_MCP_VERSION}" dependencies.playwright)"
  [ -n "$PW_VERSION" ] || die "Could not find the playwright version for @playwright/mcp@${PW_MCP_VERSION}"
  npx -y "playwright@${PW_VERSION}" install-deps chromium
fi

log "Tailscale (installed, not connected yet)"
if ! command -v tailscale >/dev/null 2>&1; then
  curl -fsSL https://tailscale.com/install.sh -o /tmp/tailscale-install.sh
  sh /tmp/tailscale-install.sh
  rm -f /tmp/tailscale-install.sh
fi

# ---------------------------------------------------------------- security
log "Firewall (public SSH open for now, closed later by 30-root-lockdown.sh)"
ufw default deny incoming >/dev/null
ufw default allow outgoing >/dev/null
if ! grep -q 'tailscale0' <<<"$(ufw status)"; then
  ufw allow OpenSSH >/dev/null       # not locked down yet: public SSH allowed
fi
ufw allow 41641/udp comment 'tailscale direct' >/dev/null
ufw --force enable >/dev/null

log "fail2ban on sshd"
cat > /etc/fail2ban/jail.d/90-devbox.local <<'EOF'
[sshd]
enabled = true
backend = systemd
maxretry = 5
bantime = 1h
EOF
systemctl enable fail2ban >/dev/null 2>&1 || true
systemctl restart fail2ban || warn "fail2ban did not start (not blocking): journalctl -u fail2ban"

log "Automatic security updates"
cat > /etc/apt/apt.conf.d/20auto-upgrades <<'EOF'
APT::Periodic::Update-Package-Lists "1";
APT::Periodic::Unattended-Upgrade "1";
EOF

if [ -n "$TIMEZONE" ]; then
  timedatectl set-timezone "$TIMEZONE" 2>/dev/null || warn "Could not set the timezone to $TIMEZONE."
fi

# ---------------------------------------------------------------- done
log "Done"
if [ -f "$SUDOERS_FILE" ]; then SUDO_STATE="without password"; else SUDO_STATE="with password"; fi
echo "User    : $DEV_USER (sudo $SUDO_STATE)"
if [ -f "$LOCK_MARK" ]; then
  echo "SSH     : keys only, $DEV_USER only, MaxSessions 20, SFTP enabled"
else
  echo "SSH     : keys only, $DEV_USER + $INITIAL_USER (until --lock-ssh), MaxSessions 20, SFTP enabled"
fi
if [ "$ARCH" = amd64 ]; then echo "Browser : $(google-chrome-stable --version 2>/dev/null)"; else echo "Browser : Playwright Chromium (arm64, not tested end to end)"; fi
echo "Node    : $(node -v)   gh : $(gh --version | head -n1)"
if [ -f /var/run/reboot-required ]; then
  echo "A reboot is recommended (kernel updated): sudo reboot"
fi
